/**
 * SPA-shell fallback guard.
 *
 * The service worker will only store a navigation response as the reusable
 * HTML shell when the response carries `X-Nexus-Spa-Shell: 1` (see the
 * `cacheableResponse.headers` option on the NetworkFirst navigation route in
 * `react-frontend/vite.config.ts`). Without that marker the runtime shell
 * cache is never populated, and `precacheFallback` hands back the *precached*
 * index.html belonging to whichever build installed the worker. After a deploy
 * that shell points at asset filenames the server has already deleted, so the
 * app cannot boot at all.
 *
 * That is not hypothetical. Until 2026-09-13 `nginx.bluegreen.conf` set the
 * marker inside `location = /` and `location /`, but both blocks end in an
 * unconditional `return 421` and the response is actually generated by the
 * `@spa_shell` named location — whose own `add_header` set replaces theirs
 * (nginx does not inherit `add_header` into a block that defines any). The
 * marker never reached a browser, and `nexus-public-html-shell-v3` did not
 * exist in production. The previous version of this file asserted only that
 * the *string* appeared somewhere in the config text, so it could not have
 * caught it — and it was not wired into any command, so it never ran.
 *
 * The checks below therefore verify the header on the block that actually
 * produces the response, not merely its presence in the file.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
let failures = 0;

function read(path) {
  return readFileSync(join(root, path), 'utf8');
}

function assert(condition, message) {
  if (!condition) {
    failures += 1;
    console.error(`FAIL: ${message}`);
  }
}

/**
 * Extract the body of a single nginx block by brace matching, so a check can
 * ask "does *this* block set the header" rather than searching the whole file.
 */
function extractBlock(text, header) {
  const start = text.indexOf(header);
  if (start === -1) return null;
  const open = text.indexOf('{', start);
  if (open === -1) return null;

  let depth = 0;
  for (let i = open; i < text.length; i += 1) {
    if (text[i] === '{') depth += 1;
    else if (text[i] === '}') {
      depth -= 1;
      if (depth === 0) return text.slice(open + 1, i);
    }
  }
  return null;
}

const SHELL_MARKER = 'add_header X-Nexus-Spa-Shell "1"';

for (const file of ['react-frontend/nginx.conf', 'react-frontend/nginx.bluegreen.conf']) {
  const text = read(file);

  assert(
    text.includes('/_spa.html'),
    `${file} must serve the clean SPA shell before falling back to rendered index.html`,
  );
  assert(
    text.includes(SHELL_MARKER),
    `${file} must mark SPA-shell navigation responses so Workbox can cache a fresh shell`,
  );

  // A try_files chain that ends at the SPA shell must prefer the clean
  // /_spa.html. Chains that hand off to @spa_shell are prerender snapshot
  // lookups — they delegate rather than serve the shell themselves.
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('try_files') || !trimmed.includes('/index.html')) continue;
    if (trimmed.includes('@spa_shell')) continue;
    assert(
      trimmed.includes('/_spa.html'),
      `${file} try_files line must prefer /_spa.html before /index.html: ${trimmed}`,
    );
  }

  // THE CHECK THAT WAS MISSING. Every block that can generate an SPA-shell
  // navigation response must set the marker itself. nginx `add_header` does
  // not inherit into a block that declares any of its own, and an internal
  // redirect (error_page -> @named) is served by the target block, so a marker
  // declared anywhere else is dead.
  const shellBlock = extractBlock(text, 'location @spa_shell');
  if (shellBlock !== null) {
    assert(
      shellBlock.includes(SHELL_MARKER),
      `${file} location @spa_shell generates the SPA shell response and must set the marker itself — `
      + 'a marker in location = / or location / is discarded by nginx on internal redirect',
    );
    assert(
      shellBlock.includes('add_header Vary "User-Agent"'),
      `${file} location @spa_shell serves bots and users different bodies at one URL, so it must Vary on User-Agent`,
    );
  }

  // Guard against the exact regression: the marker present ONLY in a block
  // whose response is produced elsewhere.
  const rootBlock = extractBlock(text, 'location = / {');
  if (rootBlock !== null && /\breturn\s+421\b/.test(rootBlock)) {
    assert(
      !rootBlock.includes(SHELL_MARKER),
      `${file} location = / hands off via "return 421" — an ${SHELL_MARKER} here never reaches the browser `
      + 'and misleads the next reader. Set it on @spa_shell instead.',
    );
  }
}

const viteConfig = read('react-frontend/vite.config.ts');
const cacheNameMatch = viteConfig.match(/cacheName: '(nexus-[a-z-]*html-shell-v\d+)'/);
assert(
  cacheNameMatch !== null,
  'vite.config.ts must name the HTML-shell runtime cache nexus-…-html-shell-v<n>, '
  + 'and bump <n> when the shell contract changes so older cached shells are abandoned',
);
assert(
  viteConfig.includes("headers: { 'X-Nexus-Spa-Shell': '1' }"),
  'vite.config.ts must only cache navigation HTML explicitly marked as the SPA shell',
);

const prerenderScript = read('react-frontend/scripts/prerender.mjs');
assert(
  prerenderScript.includes('SPA_FALLBACK_PATH') && prerenderScript.includes('writeSpaFallback'),
  'prerender.mjs must always write dist/_spa.html, including when NEXUS_SKIP_PRERENDER is set',
);

if (failures > 0) {
  console.error(`\nSPA shell fallback checks FAILED (${failures}).`);
  process.exit(1);
}

console.log(
  `SPA shell fallback checks passed (HTML shell cache: ${cacheNameMatch[1]}).`,
);
