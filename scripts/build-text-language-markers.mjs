/**
 * Builds the "distinctive everyday words" list behind isClearlyWrittenIn()
 * (react-frontend/src/lib/textLanguage). A word belongs to a language when it is
 * common there (in at least 0.2% of sentences) and at least 8 times rarer in
 * every other language listed below; up to 250 per language.
 *
 * Source: Tatoeba sentence exports (https://tatoeba.org, CC-BY 2.0 FR). Only
 * word-frequency facts are kept, never sentences. Download the per-language
 * files first, e.g.
 *   https://downloads.tatoeba.org/exports/per_language/eng/eng_sentences.tsv.bz2
 * decompress them to <dir>/<code>.tsv, then:
 *   node scripts/build-text-language-markers.mjs <dir> [--evaluate]
 *
 * The split is seeded, so the same downloads give the same list. --evaluate
 * reports how the rule does on the held-out half (never used for learning).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'react-frontend', 'src', 'lib', 'textLanguage', 'markers.json');

// ISO 639-3 Tatoeba codes. The first ten are languages members read the platform
// in; the rest are languages a member might write that resemble them.
export const LANGUAGES = [
  'eng', 'gle', 'deu', 'fra', 'ita', 'por', 'spa', 'nld', 'pol', 'ara',
  'glg', 'cat', 'afr', 'cym', 'gla', 'sco', 'ast', 'ron', 'oci', 'eus', 'dan', 'swe', 'nob', 'fry',
  'tur', 'ind', 'swh', 'hun', 'ces', 'glv', 'bre', 'lat', 'epo', 'ltz', 'isl', 'pes', 'urd',
];
/** Languages members read the platform in (Japanese is judged by script). */
const READING = ['eng', 'gle', 'deu', 'fra', 'ita', 'por', 'spa', 'nld', 'pol', 'ara'];
const VOCABULARY_SIZE = Number(process.env.VOCABULARY_SIZE || 5000);
const TRAIN = 20000;
const MIN_SHARE = 0.002;
const DISTINCTNESS = 8;
const PER_LANGUAGE = 250;

let seed = 42;
const random = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const tokens = (text) => text.toLowerCase().replace(/[’‘`]/g, "'").match(/[\p{L}]+(?:'[\p{L}]+)*/gu) || [];

function load(dir, code) {
  const file = path.join(dir, `${code}.tsv`);
  if (!fs.existsSync(file)) throw new Error(`Missing ${file} — download the Tatoeba export for ${code}.`);
  const rows = fs.readFileSync(file, 'utf8').split('\n').map((line) => line.split('\t')[2]).filter(Boolean);
  for (let i = rows.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [rows[i], rows[j]] = [rows[j], rows[i]];
  }
  const half = Math.min(TRAIN, Math.floor(rows.length / 2));
  return { train: rows.slice(0, half), test: rows.slice(half, half + 5000) };
}

export function learn(dir) {
  const data = Object.fromEntries(LANGUAGES.map((code) => [code, load(dir, code)]));
  const share = {};
  for (const code of LANGUAGES) {
    const counts = new Map();
    for (const sentence of data[code].train) for (const word of new Set(tokens(sentence))) counts.set(word, (counts.get(word) || 0) + 1);
    share[code] = new Map([...counts].map(([word, n]) => [word, n / data[code].train.length]));
  }
  const words = {};
  for (const code of LANGUAGES) {
    [...share[code]]
      .filter(([word, f]) => f >= MIN_SHARE && word.length >= 2
        && LANGUAGES.every((other) => other === code || (share[other].get(word) || 0) * DISTINCTNESS <= f))
      .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
      .slice(0, PER_LANGUAGE)
      .forEach(([word]) => { words[word] = code; });
  }
  // Everyday vocabulary of each reading language: the most common words, so a
  // text can be checked for being MOSTLY made of the reader's own words.
  const vocabulary = {};
  for (const code of READING) {
    vocabulary[code] = [...share[code]].filter(([word]) => word.length >= 1)
      .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
      .slice(0, VOCABULARY_SIZE).map(([word]) => word).sort();
  }
  return { data, words, vocabulary };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('Usage: node scripts/build-text-language-markers.mjs <tatoeba-dir> [--evaluate]');
    process.exit(2);
  }
  const { words, vocabulary } = learn(dir);
  const sorted = Object.fromEntries(Object.entries(words).sort(([a], [b]) => (a < b ? -1 : 1)));
  const source = 'Word frequencies from Tatoeba (https://tatoeba.org), CC-BY 2.0 FR. Generated by scripts/build-text-language-markers.mjs — do not edit by hand.';
  fs.writeFileSync(OUT, `${JSON.stringify({ _source: source, words: sorted }, null, 1)}\n`);
  console.log(`Wrote ${Object.keys(sorted).length} words to ${path.relative(ROOT, OUT)}`);
  const vocabularyDir = path.join(path.dirname(OUT), 'vocabulary');
  fs.mkdirSync(vocabularyDir, { recursive: true });
  for (const [code, list] of Object.entries(vocabulary)) {
    // One space-separated string: a third of the size of a JSON array.
    fs.writeFileSync(path.join(vocabularyDir, `${code}.json`), `${JSON.stringify({ _source: source, words: list.join(' ') })}\n`);
  }
  console.log(`Wrote ${Object.keys(vocabulary).length} vocabularies of ${VOCABULARY_SIZE} words to ${path.relative(ROOT, vocabularyDir)}`);
}
