declare(strict_types=1);

namespace Tests\Laravel\Feature\Billing;

use Illuminate\Support\Facades\DB;

/**
 * One community row in `tenants`, placed under a parent, for the billing tests.
 *
 * The slug is random, so communities made in one test never collide.
 */
trait MakesBillingCommunities
{
    private function makeCommunity(string $name, int $parentId, string $parentPath, bool $hub = false): int
    {
        $id = (int) DB::table('tenants')->insertGetId([
            'name' => $name,
            'slug' => 'auto-' . bin2hex(random_bytes(5)),
            'is_active' => 1,
            'parent_id' => $parentId,
            'allows_subtenants' => $hub ? 1 : 0,
            'depth' => substr_count($parentPath, '/') - 1,
            'created_at' => now(),
            'updated_at' => now(),
        ]);
        DB::table('tenants')->where('id', $id)->update(['path' => "{$parentPath}{$id}/"]);

        return $id;
    }
}
