'use strict';

/**
 * Build this frontend's copy of the platform feature catalogue.
 *
 * 🔴 WHY A GENERATED COPY AND NOT A DIRECT READ. The catalogue and its text live in
 * react-frontend (`src/data/featuresCatalogue.json` for the structure,
 * `public/locales/<locale>/public.json` for every string). This frontend's Docker
 * build context is `web-uk/`, so neither file is in its image — a runtime read would
 * work in dev and throw in production. The generated file is committed for the same
 * reason `src/lib/localization/generated/*.json` is.
 *
 * The structure is shared so the two /features pages cannot drift. The text is NOT
 * re-translated: all 119 features are already translated into all eleven languages
 * for the React page, and re-keying them into lang/*.php would have created a second
 * copy to keep in step and ~2,600 strings of avoidable translation work.
 *
 * Usage:
 *   node scripts/build-features-catalogue.js          # write the file
 *   node scripts/build-features-catalogue.js --check  # fail if it is out of date
 */

const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.join(__dirname, '..', '..');
const reactRoot = path.join(repoRoot, 'react-frontend');
const structurePath = path.join(reactRoot, 'src', 'data', 'featuresCatalogue.json');
const localesRoot = path.join(reactRoot, 'public', 'locales');
const outputPath = path.join(__dirname, '..', 'src', 'lib', 'generated', 'features-catalogue.json');

// The locales this frontend serves. Deliberately listed rather than read from disk:
// a locale silently disappearing from react-frontend should fail here, not quietly
// shrink the accessible site's language coverage.
const LOCALES = Object.freeze([
  'en', 'ga', 'de', 'fr', 'it', 'pt', 'es', 'nl', 'pl', 'ja', 'ar',
]);

const VALID_MATURITY = Object.freeze(['ga', 'beta', 'preview', 'dormant']);

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function build() {
  const problems = [];

  if (!fs.existsSync(structurePath)) {
    throw new Error(`Feature catalogue structure not found at ${structurePath}`);
  }
  const structure = readJson(structurePath);
  if (!Array.isArray(structure.groups) || structure.groups.length === 0) {
    throw new Error('Feature catalogue structure has no groups');
  }

  // Normalise: an item with no maturity is generally available. Making that explicit
  // here keeps the template free of "or 'ga'" fallbacks.
  const groups = structure.groups.map((group) => ({
    key: group.key,
    items: (group.items || []).map((item) => {
      const maturity = item.maturity || 'ga';
      if (!VALID_MATURITY.includes(maturity)) {
        problems.push(`${group.key}.${item.key}: unknown maturity "${maturity}"`);
      }
      return { key: item.key, maturity };
    }),
  }));

  const itemCount = groups.reduce((n, g) => n + g.items.length, 0);

  const text = {};
  for (const locale of LOCALES) {
    const file = path.join(localesRoot, locale, 'public.json');
    if (!fs.existsSync(file)) {
      problems.push(`${locale}: public.json missing`);
      continue;
    }
    const featuresPage = readJson(file).features_page;
    if (!featuresPage) {
      problems.push(`${locale}: public.json has no features_page`);
      continue;
    }

    // Every group and every item must have its text in every language. A missing
    // string would otherwise render as a blank row on a live page.
    for (const group of groups) {
      const groupText = (featuresPage.groups || {})[group.key];
      if (!groupText || !groupText.title) {
        problems.push(`${locale}: groups.${group.key}.title missing`);
        continue;
      }
      for (const item of group.items) {
        const itemText = (groupText.items || {})[item.key];
        if (!itemText || !itemText.title) {
          problems.push(`${locale}: groups.${group.key}.items.${item.key}.title missing`);
        } else if (!itemText.description) {
          problems.push(`${locale}: groups.${group.key}.items.${item.key}.description missing`);
        }
      }
    }

    text[locale] = featuresPage;
  }

  if (problems.length) {
    const shown = problems.slice(0, 20).join('\n  - ');
    const more = problems.length > 20 ? `\n  ...and ${problems.length - 20} more` : '';
    throw new Error(`Feature catalogue is incomplete:\n  - ${shown}${more}`);
  }

  const payload = {
    _README:
      'GENERATED by web-uk/scripts/build-features-catalogue.js — do not edit by hand. '
      + 'Structure from react-frontend/src/data/featuresCatalogue.json; text from '
      + 'react-frontend/public/locales/<locale>/public.json (features_page). Refresh with '
      + '`npm --prefix web-uk run build:features`; `npm --prefix web-uk run check:features` '
      + 'fails when this file is out of date.',
    locales: LOCALES,
    groupCount: groups.length,
    itemCount,
    groups,
    text,
  };

  return { payload, groups, itemCount };
}

function serialise(payload) {
  return `${JSON.stringify(payload, null, 2)}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const { payload, groups, itemCount } = build();
  const next = serialise(payload);

  if (check) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== next) {
      console.error('FAIL: src/lib/generated/features-catalogue.json is out of date.');
      console.error('      Run `npm --prefix web-uk run build:features` and commit the result.');
      process.exit(1);
    }
    console.log(`Feature catalogue up to date: ${groups.length} groups, ${itemCount} features, ${LOCALES.length} locales.`);
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, next, 'utf8');
  console.log(`Feature catalogue written: ${groups.length} groups, ${itemCount} features, ${LOCALES.length} locales.`);
}

main();
