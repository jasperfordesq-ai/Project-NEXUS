'use strict';

/**
 * Build this frontend's copy of the two static legal pages both frontends publish:
 * account deletion, and child safety standards.
 *
 * 🔴 WHY THIS IS GENERATED RATHER THAN TRANSLATED INTO lang/*.php LIKE THE OTHER
 * ACCESSIBLE PAGES. This is compliance copy, not UI chrome. It names a real legal
 * entity, a charity number, a registered address, a Google Play package id, a
 * designated child-safety contact and an effective date, and the child-safety page is
 * the copy Google Play is pointed at. Two hand-maintained copies of that in two
 * frontends is a compliance problem waiting to happen: the day they disagree, one of
 * them is telling members something untrue about deleting their data or about how a
 * child-safety report is handled. So there is one source, and it is React's.
 *
 * These are NOT legal documents in the API's sense — `account_deletion` and
 * `child_safety` are not in `LegalController::VALID_TYPES`, so unlike terms or privacy
 * there is no per-community version to fetch and no fallback to arrange.
 *
 * Usage:
 *   node scripts/build-legal-text.js          # write the file
 *   node scripts/build-legal-text.js --check  # fail if it is out of date
 */

const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.join(__dirname, '..', '..');
const localesRoot = path.join(repoRoot, 'react-frontend', 'public', 'locales');
const outputPath = path.join(__dirname, '..', 'src', 'lib', 'generated', 'legal-text.json');

const LOCALES = Object.freeze([
  'en', 'ga', 'de', 'fr', 'it', 'pt', 'es', 'nl', 'pl', 'ja', 'ar',
]);

const PAGES = Object.freeze(['account_deletion', 'child_safety']);

/**
 * React stores its ordered lists as objects keyed "0", "1", "2" (an i18next habit).
 * Turn them back into arrays so a template can just loop.
 */
function normaliseLists(block) {
  const out = {};
  for (const [key, value] of Object.entries(block)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      const indices = Object.keys(value);
      const isOrderedList = indices.every((k) => /^\d+$/.test(k));
      out[key] = isOrderedList
        ? indices.sort((a, b) => Number(a) - Number(b)).map((k) => value[k])
        : value;
      continue;
    }
    out[key] = value;
  }
  return out;
}

function build() {
  const problems = [];

  const englishPath = path.join(localesRoot, 'en', 'legal.json');
  if (!fs.existsSync(englishPath)) throw new Error(`Not found: ${englishPath}`);
  const english = JSON.parse(fs.readFileSync(englishPath, 'utf8'));

  const expected = {};
  for (const page of PAGES) {
    if (!english[page]) throw new Error(`en/legal.json has no "${page}" block`);
    expected[page] = Object.keys(english[page]);
  }

  const text = {};
  for (const locale of LOCALES) {
    const file = path.join(localesRoot, locale, 'legal.json');
    if (!fs.existsSync(file)) {
      problems.push(`${locale}: legal.json missing`);
      continue;
    }
    const data = JSON.parse(fs.readFileSync(file, 'utf8'));
    text[locale] = {};

    for (const page of PAGES) {
      const block = data[page];
      if (!block) {
        problems.push(`${locale}: "${page}" block missing`);
        continue;
      }
      // 🔴 Every key, in every language. A missing string here is a blank line in a
      // compliance statement, which is worse than an obviously untranslated one.
      for (const key of expected[page]) {
        if (block[key] === undefined || block[key] === '') {
          problems.push(`${locale}: ${page}.${key} missing`);
        }
      }
      text[locale][page] = normaliseLists(block);
    }
  }

  if (problems.length) {
    const shown = problems.slice(0, 20).join('\n  - ');
    const more = problems.length > 20 ? `\n  ...and ${problems.length - 20} more` : '';
    throw new Error(`Legal page text is incomplete:\n  - ${shown}${more}`);
  }

  return {
    _README:
      'GENERATED by web-uk/scripts/build-legal-text.js from '
      + 'react-frontend/public/locales/<locale>/legal.json — do not edit by hand. These two '
      + 'pages are compliance copy published by BOTH frontends and must not exist as two '
      + 'hand-maintained copies. Refresh with `npm --prefix web-uk run build:legal-text`; '
      + '`npm --prefix web-uk run check:legal-text` fails when it is out of date.',
    locales: LOCALES,
    pages: PAGES,
    text,
  };
}

function serialise(payload) {
  return `${JSON.stringify(payload, null, 2)}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  const payload = build();
  const next = serialise(payload);

  if (check) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== next) {
      console.error('FAIL: src/lib/generated/legal-text.json is out of date.');
      console.error('      Run `npm --prefix web-uk run build:legal-text` and commit the result.');
      process.exit(1);
    }
    console.log(`Legal page text up to date: ${PAGES.length} pages, ${LOCALES.length} locales.`);
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, next, 'utf8');
  console.log(`Legal page text written: ${PAGES.length} pages, ${LOCALES.length} locales.`);
}

main();
